/**
 * Sinh js/vendor/lucide-subset.js: chỉ các icon Lucide mà trang chủ + header cần, thay cho
 * https://unpkg.com/lucide@latest (~100KB, tải chặn parser, phiên bản trôi theo release mới).
 * API tương thích: window.lucide.createIcons() thay mọi [data-lucide] bằng SVG giống Lucide gốc.
 *
 * Chạy: node scripts/build-lucide-subset.js   (tải lucide@VERSION từ unpkg)
 * Thêm icon mới cho trang chủ/header → thêm tên vào ICONS rồi chạy lại.
 */
const fs = require('fs');
const https = require('https');
const path = require('path');
const vm = require('vm');

const VERSION = '1.48.0';
const SOURCE_URL = `https://unpkg.com/lucide@${VERSION}/dist/umd/lucide.min.js`;
const OUT_FILE = path.join(__dirname, '..', 'js', 'vendor', 'lucide-subset.js');

const ICONS = [
  // index.html
  'arrow-right', 'bell-ring', 'calendar-days', 'calendar-heart', 'chevron-left', 'chevron-right',
  'download', 'gamepad-2', 'gift', 'grid-2x2', 'layout-dashboard', 'layout-grid', 'mail', 'mail-open',
  'message-circle', 'share-2', 'shopping-bag', 'smartphone', 'sparkles', 'store', 'sun', 'wallet',
  // components/header.html
  'book-open', 'calendar', 'chevron-down', 'globe', 'newspaper', 'qr-code', 'timer', 'utensils-crossed',
];

function download(url) {
  return new Promise((resolve, reject) => {
    https.get(url, (res) => {
      if (res.statusCode >= 300 && res.statusCode < 400 && res.headers.location) {
        resolve(download(new URL(res.headers.location, url).href));
        return;
      }
      if (res.statusCode !== 200) {
        reject(new Error(`GET ${url} → ${res.statusCode}`));
        return;
      }
      let body = '';
      res.setEncoding('utf8');
      res.on('data', (chunk) => { body += chunk; });
      res.on('end', () => resolve(body));
    }).on('error', reject);
  });
}

const toPascal = (name) => name.split('-').map((part) => part[0].toUpperCase() + part.slice(1)).join('');

async function main() {
  const source = process.env.LUCIDE_UMD ? fs.readFileSync(process.env.LUCIDE_UMD, 'utf8') : await download(SOURCE_URL);
  const context = {};
  vm.createContext(context);
  vm.runInContext(source, context);

  const icons = {};
  for (const name of [...ICONS].sort()) {
    const node = context.lucide.icons[toPascal(name)];
    if (!node) throw new Error(`build-lucide-subset: icon "${name}" not found in lucide@${VERSION}`);
    icons[name] = node;
  }

  const output = `/* Generated by scripts/build-lucide-subset.js from lucide@${VERSION} (ISC License, https://lucide.dev). Do not edit. */
(function () {
  if (window.lucide && window.lucide.createIcons) return;
  var ICONS = ${JSON.stringify(icons)};
  var DEFAULTS = { xmlns: 'http://www.w3.org/2000/svg', width: 24, height: 24, viewBox: '0 0 24 24', fill: 'none', stroke: 'currentColor', 'stroke-width': 2, 'stroke-linecap': 'round', 'stroke-linejoin': 'round' };
  function build(tag, attrs, children) {
    var el = document.createElementNS('http://www.w3.org/2000/svg', tag);
    for (var key in attrs) el.setAttribute(key, String(attrs[key]));
    (children || []).forEach(function (child) { el.appendChild(build(child[0], child[1], child[2])); });
    return el;
  }
  function replace(el) {
    var name = el.getAttribute('data-lucide');
    var node = ICONS[name];
    if (!node) return;
    var attrs = {}, key, own = {}, hasAria = false;
    for (key in DEFAULTS) attrs[key] = DEFAULTS[key];
    attrs['data-lucide'] = name;
    Array.prototype.forEach.call(el.attributes, function (attr) {
      own[attr.name] = attr.value;
      if (attr.name.indexOf('aria-') === 0 || attr.name === 'role' || attr.name === 'title') hasAria = true;
    });
    if (!hasAria) attrs['aria-hidden'] = 'true';
    for (key in own) attrs[key] = own[key];
    attrs['class'] = ['lucide', 'lucide-' + name].concat((own['class'] || '').split(' ')).filter(function (c, i, all) { return c && all.indexOf(c) === i; }).join(' ');
    if (el.parentNode) el.parentNode.replaceChild(build('svg', attrs, node), el);
  }
  function createIcons(options) {
    var root = (options && options.root) || document;
    Array.prototype.forEach.call(root.querySelectorAll('[data-lucide]:not(svg)'), replace);
  }
  window.lucide = { createIcons: createIcons, icons: ICONS };
})();
`;

  fs.mkdirSync(path.dirname(OUT_FILE), { recursive: true });
  fs.writeFileSync(OUT_FILE, output, 'utf8');
  console.log(`build-lucide-subset: ${ICONS.length} icons → ${path.relative(process.cwd(), OUT_FILE)} (${output.length} bytes)`);
}

main().catch((error) => {
  console.error(error.message);
  process.exit(1);
});
